    private static final MajorDirection[] ALL = {
        IT, CIVIL, ENGINEERING, MEDICAL, BUSINESS, LAW,
        EDUCATION, ART, AGRICULTURE, SCIENCE, HUMANITIES, GENERAL
    };

    /** 根据专业名解析方向；无法判断时返回通用模板 */
    public static MajorDirection resolve(String majorName) {
        if (majorName != null && !majorName.trim().isEmpty()) {
            for (MajorDirection direction : ALL) {
                if (direction != GENERAL && direction.pattern.matcher(majorName).find()) {
                    return direction;
                }
            }
        }
        return GENERAL;
    }

    /** 判断是否计算机 / 电子信息方向（该方向沿用数据库里的 9 个能力字段） */
    public static boolean isIT(String majorName) {
        return resolve(majorName) == IT;
    }
