/** 扁平化的专业名单，用于生成课程数据；由 majorCategories 派生，不单独维护 */
export const allMajors = (() => {
  const seen = new Set()
  const list = []
  for (const category of majorCategories) {
    for (const name of category.majors) {
      if (seen.has(name)) continue
      seen.add(name)
      list.push(name)
    }
  }
  return list
})()
